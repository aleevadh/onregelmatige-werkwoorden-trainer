let currentVerb, fromCategory, toCategory;
let awaitingCheck = true;

function nextQuestion() {
  document.getElementById("feedback").textContent = "";
  document.getElementById("answer").value = "";

  currentVerb = verbs[Math.floor(Math.random() * verbs.length)];
  fromCategory = "infinitief";

  const targetCategories = ["imperfectum_sg", "imperfectum_pl", "perfectum"];
  toCategory =
    targetCategories[Math.floor(Math.random() * targetCategories.length)];

  document.getElementById(
    "question"
  ).innerHTML = `<u>Werkwoorden</u> > ${currentVerb[fromCategory]}<br><u>Conjugeer</u> in > ${categoryLabels[toCategory]}`;

  awaitingCheck = true;
  document.getElementById("button").textContent = "✔";
}

function checkAnswer() {
  const userAnswer = document.getElementById("answer").value.trim();
  const correctAnswer = currentVerb[toCategory];
  const feedback = document.getElementById("feedback");

  if (userAnswer.toLowerCase() === correctAnswer.toLowerCase()) {
    feedback.textContent = "Correct!";
  } else {
    feedback.textContent = `No, het juiste antwoord is: ${correctAnswer}`;
  }

  awaitingCheck = false;
  document.getElementById("button").textContent = "Next";
}

document.addEventListener("DOMContentLoaded", () => {
  const btn = document.getElementById("button");

  btn.addEventListener("click", () => {
    if (awaitingCheck) {
      checkAnswer();
    } else {
      nextQuestion();
    }
  });

  document.getElementById("answer").addEventListener("keypress", (e) => {
    if (e.key === "Enter") {
      if (awaitingCheck) {
        checkAnswer();
      } else {
        nextQuestion();
      }
    }
  });

  nextQuestion();
});
